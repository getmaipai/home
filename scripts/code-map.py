#!/usr/bin/env python3
"""Writes docs/dev/code-map.md: where each screen, package page and exported component lives, so a model (or a person) can
go straight to the file instead of searching the repo.

  python3 scripts/code-map.py           rewrite docs/dev/code-map.md
  python3 scripts/code-map.py --check   exit 1 if the file is stale (run by scripts/local-land.py before landing)

Standard library only. Every entry is read from the code itself, so the map cannot describe something that is not there.
"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "dev", "code-map.md")
EXPORT = re.compile(r"^export\s+(?:default\s+)?(?:async\s+)?(?:function|const|class)\s+([A-Za-z_][A-Za-z0-9_]*)", re.M)


def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, "/")


def package_pages():
    rows = []
    for page in sorted(glob.glob(os.path.join(ROOT, "backend", "packages", "*", "pages", "*.json"))):
        try:
            data = json.load(open(page))
        except (OSError, ValueError):
            continue
        pkg = page.split(os.sep)[-3]
        title = data.get("title") or data.get("id") or os.path.basename(page)
        rows.append("| `%s` | %s | %s |" % (rel(page), pkg, str(title).replace("|", "/")))
    return rows


def frontend_screens():
    rows = []
    for f in sorted(glob.glob(os.path.join(ROOT, "frontend", "src", "**", "*.tsx"), recursive=True)):
        if f.endswith((".test.tsx", ".test.ts")) or "/preview/" in f or "/dev/" in f:
            continue
        names = EXPORT.findall(open(f, errors="replace").read())
        if names:
            rows.append("| `%s` | %s |" % (rel(f), ", ".join(names[:6])))
    return rows


def backend_units():
    rows = []
    for f in sorted(glob.glob(os.path.join(ROOT, "backend", "src", "lib", "**", "*.ts"), recursive=True)):
        if f.endswith(".test.ts"):
            continue
        names = EXPORT.findall(open(f, errors="replace").read())
        if names:
            rows.append("| `%s` | %s |" % (rel(f), ", ".join(names[:6])))
    return rows


def render():
    head = ("# Code map\n\n"
            "Generated by `scripts/code-map.py`; do not edit by hand. Find a screen or feature here first, then open the file. "
            "Search for a visible word only after this map has not found it.\n\n"
            "Where display rules apply: a package screen (news, music, buddy and the rest) is drawn from the page JSON in its `pages` "
            "folder, through the shared renderer in `commons/ui`. Changing its layout can mean the JSON, the shared element, or both.\n\n")
    return (head
            + "## Package pages (backend/packages)\n\n| File | Package | Title |\n|---|---|---|\n" + "\n".join(package_pages()) + "\n\n"
            + "## Frontend screens and components (frontend/src)\n\n| File | Exported names |\n|---|---|\n" + "\n".join(frontend_screens()) + "\n\n"
            + "## Backend units (backend/src/lib)\n\n| File | Exported names |\n|---|---|\n" + "\n".join(backend_units()) + "\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            print("docs/dev/code-map.md is stale: run python3 scripts/code-map.py and commit it"); sys.exit(1)
        print("code map is current"); sys.exit(0)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print("wrote", rel(OUT), len(text.splitlines()), "lines")
