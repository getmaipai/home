#!/usr/bin/env python3
"""Writes scripts/INDEX.md: one line per script, read from the script's own `Intent:` header, else its first comment line.

  python3 scripts/make-scripts-index.py           rewrite scripts/INDEX.md
  python3 scripts/make-scripts-index.py --check   exit 1 if the file is stale (run by scripts/check.sh)

Test files (*.test.ts, *_test.py) and fixtures are left out. Standard library only.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPTS = os.path.join(ROOT, "scripts")
OUT = os.path.join(SCRIPTS, "INDEX.md")
EXT = (".sh", ".py", ".ts", ".mjs", ".swift")
DIRS = {
    "gate": "Gate internals: shard runner, stamps, flake ledger, release gate, worktree lock.",
    "jobs": "Heavy dev jobs and the dev checkout lease (job.sh, lease.sh).",
    "lib": "Shell helpers sourced by other scripts (deps, git net, host memory, mode, warm install).",
    "hooks": "Git and Claude hooks (guard-shared.sh).",
    "libexec": "Helpers the live install runs (rollback pruning).",
    "pack": "Companion pack builders and validators.",
    "studio": "Studio host guard and host tuning.",
    "tests": "Shared fixtures for the lander, watcher and worktree tests.",
    "engine-computer": "Engine pairing helpers for the computer-use tier.",
    "types": "Ambient type declarations for the scripts.",
}

# Scripts on the safety surface (scripts/wt.sh WT_T2_GLOBS) keep no header edits; their line is here.
FIXED = {"lander.sh": "the one lander daemon per machine: checks each queued branch and fast-forwards main, pushing it to GitHub."}

def describe(path):
    if os.path.basename(path) in FIXED:
        return FIXED[os.path.basename(path)]
    try:
        lines = open(path, errors="replace").read().splitlines()[:40]
    except OSError:
        return ""
    for l in lines:
        m = re.match(r"^\s*(?:#|//|\*|/\*\*?)\s*Intent:\s*(.+)$", l)
        if m:
            return clean(m.group(1))
    buf = []
    for l in lines:
        s = l.strip()
        if s.startswith("#!") or (not s and not buf):
            continue
        if s.startswith('"""'):
            body = s.strip('"').strip()
            if body:
                buf.append(body)
            continue
        m = re.match(r"^(?:#|//|/\*\*?|\*)\s?(.*)$", s)
        if m and m.group(1).strip() and not m.group(1).strip().startswith(("shellcheck", "eslint", "@ts-", "usage", "Usage")):
            buf.append(m.group(1).strip())
            if len(buf) >= 3 or re.search(r"[.!?]$", buf[-1]):
                break
            continue
        break
    return clean(" ".join(buf)) if buf else ""

def clean(t):
    t = t.strip().rstrip("*/").strip().replace("|", "/")
    cut = re.split(r"(?<=[.;])\s", t, maxsplit=1)[0]
    return (cut if len(cut) > 20 else t)[:140]

def build():
    rows = []
    for name in sorted(os.listdir(SCRIPTS)):
        p = os.path.join(SCRIPTS, name)
        if os.path.isdir(p):
            if name in DIRS:
                rows.append("| `scripts/%s/` | %s |" % (name, DIRS[name]))
            continue
        if not name.endswith(EXT) or ".test." in name or name.endswith(("_test.py", "Fixtures.ts")) or name == "INDEX.md":
            continue
        rows.append("| `scripts/%s` | %s |" % (name, describe(p) or "(no header: add an `Intent:` line)"))
    head = ("# Scripts index\n\nGenerated by `scripts/make-scripts-index.py`; do not edit by hand. The text is each script's `Intent:` header or, where it has none, "
            "its first comment line. How to run the delivery scripts and what goes wrong: [docs/dev/process.md](../docs/dev/process.md).\n\n| Script | What it does |\n|---|---|\n")
    return head + "\n".join(rows) + "\n"

if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("scripts/INDEX.md is stale: run python3 scripts/make-scripts-index.py and commit it"); sys.exit(1)
        print("scripts index is current")
    else:
        open(OUT, "w").write(text)
        print("wrote scripts/INDEX.md (%d scripts)" % (text.count("\n| `")))
