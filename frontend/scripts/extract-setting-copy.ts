// `bun run i18n:settings` (design note section 10): writes src/lib/settingCopy.generated.ts from the live settings registry
// (spec plus Home keys), the reason vocabulary and the settings areas. Never hand-edit the output; `bun run i18n:check` fails when it is stale.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { getRegistry } from "../../backend/src/lib/settingsRegistry";
import { SETTINGS_AREAS } from "../src/shell/pages/settings/settingsAreas";
import { titleCaseOption } from "@maipai/ui/src/settings/SettingField";

export const GENERATED_PATH = "src/lib/settingCopy.generated.ts";
const q = JSON.stringify;
const VOCAB = JSON.parse(readFileSync("node_modules/@maipai/spec/vocab/setting-reasons.json", "utf8")) as Record<string, Record<string, Record<string, string>>>;

export function buildGenerated(): string {
  const copy: [string, string][] = [];
  const add = (id: string, en: unknown) => { if (typeof en === "string" && en.trim()) copy.push([id, en]); };
  for (const key of [...getRegistry()].sort((a, b) => a.key.localeCompare(b.key))) {
    const p = `setting.${key.key}`;
    add(`${p}.label`, key.label);
    add(`${p}.help`, key.help);
    const c = (key.copy ?? {}) as Record<string, unknown>;
    for (const field of ["does", "does_child", "does_teen", "title", "what_is_stored", "consent_adult_self", "consent_teen_self", "consent_child_parent", "consent_guest"]) add(`${p}.${field}`, c[field]);
    for (const [value, text] of Object.entries((c.options ?? {}) as Record<string, string>)) add(`${p}.option.${value}`, text);
    const labels = (c.option_labels ?? {}) as Record<string, string>;
    const options = (key.range as { options?: string[] } | undefined)?.options ?? [];
    for (const value of options) add(`${p}.option_label.${value}`, labels[value] ?? titleCaseOption(value));
    for (const [value, text] of Object.entries(labels)) if (!options.includes(value)) add(`${p}.option_label.${value}`, text);
  }
  const reasons: [string, string][] = [];
  for (const [code, readers] of Object.entries(VOCAB)) for (const [reader, lines] of Object.entries(readers)) for (const [variant, text] of Object.entries(lines)) reasons.push([`setting.reason.${code}.${reader}.${variant}`, text]);
  const areaWords = new Set<string>();
  const walk = (node: unknown) => {
    if (Array.isArray(node)) return node.forEach(walk);
    if (node && typeof node === "object") for (const [k, v] of Object.entries(node)) {
      if ((k === "title" || k === "label") && typeof v === "string") areaWords.add(v); else walk(v);
    }
  };
  walk(SETTINGS_AREAS);
  const lines = [
    "// GENERATED by `bun run i18n:settings` (scripts/extract-setting-copy.ts) from the settings registry. Do not edit by hand.",
    'import { i18n } from "@lingui/core";',
    "",
    "/** Registry copy by id: `en` is the spec English (a translation is used only while the incoming text still equals it). */",
    "export const SETTING_COPY: Record<string, { en: string; t: () => string }> = {",
    ...copy.map(([id, en]) => `  ${q(id)}: { en: ${q(en)}, t: () => i18n._({ id: ${q(id)}, message: ${q(en)} }) },`),
    "};",
    "",
    "/** Reason-line templates ({admin} and {person} are filled by the reader). */",
    "export const SETTING_REASONS: { en: string; t: (values: { admin?: string; person?: string }) => string }[] = [",
    ...reasons.map(([id, en]) => `  { en: ${q(en)}, t: (values) => i18n._({ id: ${q(id)}, message: ${q(en)}, values }) },`),
    "];",
    "",
    "/** Settings area, group, section, tab and card names by English text. */",
    "export const AREA_COPY: Record<string, () => string> = {",
    ...[...areaWords].sort().map((en) => `  ${q(en)}: () => i18n._({ id: ${q(`area.${en}`)}, message: ${q(en)} }),`),
    "};",
    "",
  ];
  return lines.join("\n");
}

/** False when the committed generated file differs from what the registry produces now (a new or edited key, reason line or area label). */
export function generatedIsCurrent(path = GENERATED_PATH): boolean {
  return existsSync(path) && readFileSync(path, "utf8") === buildGenerated();
}

if (import.meta.main) {
  writeFileSync(GENERATED_PATH, buildGenerated());
  console.log(`Wrote ${GENERATED_PATH}.`);
}
